import json

Q = []

def sa(qid, cat, diff, text, a, b, expl=None, fig=None):
    """단답형 — 답은 a×b"""
    p = a * b
    item = {
        'id': qid, 'category': cat, 'difficulty': diff, 'type': 'short_answer',
        'inputMode': 'integer', 'question': text, 'choices': [], 'answer': str(p),
        'explanation': expl or f'{a} × {b} = {p}.',
    }
    if fig: item['figure'] = fig
    Q.append(item)

def mc(qid, cat, diff, text, a, b, choices, expl=None, fig=None, unit=''):
    """객관식 — choices 안에 a×b 값이 정확히 하나 있어야 한다"""
    p = a * b
    want = f'{p}{unit}'
    assert choices.count(want) == 1, f'{qid}: 보기에 정답 {want}가 정확히 하나 있어야 함 → {choices}'
    Q.append({
        'id': qid, 'category': cat, 'difficulty': diff, 'type': 'multiple_choice',
        'question': text, 'choices': choices, 'answer': choices.index(want),
        'explanation': expl or f'{a} × {b} = {p}.',
        **({'figure': fig} if fig else {}),
    })

def mcx(qid, cat, diff, text, choices, correct, expl):
    """개념형 객관식 — 계산이 아닌 보기(교환법칙 등)"""
    assert choices.count(correct) == 1, f'{qid}: 정답 보기 중복/누락'
    Q.append({
        'id': qid, 'category': cat, 'difficulty': diff, 'type': 'multiple_choice',
        'question': text, 'choices': choices, 'answer': choices.index(correct),
        'explanation': expl,
    })

