# ── 검증
assert len(Q) == 60, len(Q)
# 계산형 문항은 목표 식(a × b = 결과)이 풀이에 그대로 보여야 한다
import re as _re
for _q in Q:
    if _q['type'] == 'multiple_choice' and _re.fullmatch(r'\d+\D*', _q['choices'][_q['answer']]):
        _p = _re.sub(r'\D', '', _q['choices'][_q['answer']])
        assert _re.search(rf'\d+\s*×\s*\d+\s*=\s*{_p}(?!\d)', _q['explanation']), \
            f"{_q['id']}: 풀이에 '… = {_p}' 식이 없음 → {_q['explanation']}"
ids = [q['id'] for q in Q]
assert len(set(ids)) == 60, '중복 id'
for q in Q:
    if q['type'] == 'short_answer':
        assert q['inputMode'] == 'integer', q['id']
        assert q['answer'].isdigit(), q['id']
        # 답이 풀이에 등장하는지
        assert q['answer'] in q['explanation'], (q['id'], q['answer'], q['explanation'])
    else:
        assert isinstance(q['answer'], int) and 0 <= q['answer'] < len(q['choices']), q['id']
        assert len(q['choices']) == 5, q['id']
        assert len(set(q['choices'])) == 5, (q['id'], '보기 중복')
    for fig in ([q['figure']] if 'figure' in q else []):
        assert fig['rows'] * fig['cols'] <= 81, q['id']

